"""Write docs/CHECKS.md from rules.RULES: what every finding code means and what to do about it.

    python tools/make_checks_doc.py          # rewrite the file
    python tools/make_checks_doc.py --check  # exit 1 if the file is out of date (the tests run this)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import rules  # noqa: E402

GROUPS = [
    ("Response headers", ("no-https", "no-hsts", "short-hsts", "no-csp", "weak-csp", "no-frame-protection", "no-nosniff", "no-referrer-policy", "no-permissions-policy",
                          "server-version", "x-powered-by", "cors-wildcard", "cors-wildcard-creds")),
    ("Cookies", ("cookie-no-secure", "cookie-no-httponly", "cookie-no-samesite", "cookie-over-http", "cookie-samesite-none-insecure", "cookie-prefix-misuse",
                 "cookie-broad-domain", "cookie-long-lived", "cookie-cacheable")),
    ("Page markup and forms", ("no-sri-script", "no-sri-style", "mixed-active", "mixed-passive", "iframe-no-sandbox", "tabnabbing", "form-http", "password-over-http",
                               "login-cross-origin", "form-no-csrf", "form-upload", "comment-secret", "exposed-secret", "password-in-url")),
    ("Links", ("http-downgrade", "http-external", "userinfo", "punycode", "shortener", "raw-ip", "risky-tld", "internal-address", "open-redirect", "sensitive-file",
               "admin-path", "login-path", "exec-download", "obfuscated", "long-url", "odd-port", "url-secret", "broken")),
    ("The site as a whole", ("restricted", "orphan-page", "robots-sensitive", "no-security-txt", "exposed-file", "host-unresolved")),
    ("Certificate and protocol", ("tls-expired", "tls-expiring", "tls-invalid", "tls-old-protocol", "tls-unreachable", "tls-weak-key", "tls-weak-signature")),
    ("Technologies", ("old-jquery", "old-bootstrap", "old-nginx", "old-iis", "apache-path-traversal", "eol-php", "eol-angularjs", "basic-auth-http")),
    ("DNS and e-mail (--dns)", ("email-no-spf", "email-spf-multiple", "email-spf-permissive", "email-spf-softfail", "email-spf-ptr", "email-spf-lookups", "email-no-dmarc",
                                "email-dmarc-none", "email-dmarc-invalid", "email-dmarc-partial", "email-dmarc-subdomains", "email-dmarc-no-rua", "email-no-dkim-found",
                                "email-no-mta-sts", "dns-no-caa", "dns-no-dnssec")),
]


def render() -> str:
    out = ["# What the checks mean", "",
           "Every finding has a short code, shown in reports and in the `code` field of the JSON and SARIF exports. Severity is not fixed per code: it depends on the page "
           "(a missing flag on a session cookie ranks higher than on a theme cookie). A finding says *worth a look*, not *proven vulnerable*. Accept the ones you have "
           "decided to live with (`--accepted`, see the README).", "",
           "<!-- generated by tools/make_checks_doc.py from rules.py: edit rules.py, not this file -->", ""]
    seen = set()
    for title, codes in GROUPS:
        out += [f"## {title}", ""]
        for code in codes:
            name, advice, cwes = rules.RULES[code]
            seen.add(code)
            out += [f"### `{code}`", "", f"**{name}.** {advice}" + (f" ({', '.join(cwes)})" if cwes else ""), ""]
    extra = sorted(set(rules.RULES) - seen)
    if extra:
        out += ["## Other", ""]
        for code in extra:
            name, advice, cwes = rules.RULES[code]
            out += [f"### `{code}`", "", f"**{name}.** {advice}" + (f" ({', '.join(cwes)})" if cwes else ""), ""]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    target = ROOT / "docs" / "CHECKS.md"
    text = render()
    if "--check" in sys.argv:
        ok = target.exists() and target.read_text(encoding="utf-8") == text
        print("docs/CHECKS.md is up to date" if ok else "docs/CHECKS.md is out of date: run python tools/make_checks_doc.py")
        return 0 if ok else 1
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {target} ({len(rules.RULES)} checks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
